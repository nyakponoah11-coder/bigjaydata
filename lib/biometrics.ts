import crypto from "crypto";
import { supabaseAdmin, isSupabaseConfigured } from "./supabase";

export interface BiometricCredential {
  id: string; // Base64URL credential ID
  email: string;
  deviceName: string;
  publicKey?: string;
  counter?: number;
  createdAt: string;
  lastUsedAt?: string;
}

// In-memory challenge store (5 minute expiration)
const activeChallenges = new Map<string, { timestamp: number; type: "register" | "auth" }>();
const CHALLENGE_TTL_MS = 5 * 60 * 1000;

function cleanupChallenges() {
  const now = Date.now();
  for (const [ch, meta] of activeChallenges.entries()) {
    if (now - meta.timestamp > CHALLENGE_TTL_MS) {
      activeChallenges.delete(ch);
    }
  }
}

/**
 * Creates a cryptographically random challenge for WebAuthn ceremonies
 */
export function createBiometricChallenge(type: "register" | "auth" = "auth"): string {
  cleanupChallenges();
  const challenge = crypto.randomBytes(32).toString("base64url");
  activeChallenges.set(challenge, { timestamp: Date.now(), type });
  return challenge;
}

/**
 * Verifies that a challenge was legitimately generated by the server and has not expired
 */
export function consumeBiometricChallenge(challenge: string): boolean {
  cleanupChallenges();
  if (!challenge) return false;
  const item = activeChallenges.get(challenge);
  if (!item) return false;
  activeChallenges.delete(challenge);
  return true;
}

/**
 * Retrieves all registered biometric credentials from Supabase settings
 */
export async function getEnrolledBiometricCredentials(): Promise<BiometricCredential[]> {
  if (!isSupabaseConfigured || !supabaseAdmin) {
    return [];
  }

  try {
    const { data, error } = await supabaseAdmin
      .from("settings")
      .select("store_name")
      .eq("id", "admin_biometric_credentials")
      .maybeSingle();

    if (!error && data?.store_name) {
      const parsed = JSON.parse(data.store_name);
      if (Array.isArray(parsed)) {
        return parsed;
      }
    }
  } catch (err) {
    console.warn("[Biometrics] Error fetching biometric credentials:", err);
  }

  return [];
}

/**
 * Enrolls a new biometric credential into Supabase settings
 */
export async function saveBiometricCredential(cred: BiometricCredential): Promise<boolean> {
  if (!isSupabaseConfigured || !supabaseAdmin) {
    throw new Error("Supabase is not configured to store biometric credentials.");
  }

  try {
    const existing = await getEnrolledBiometricCredentials();
    const filtered = existing.filter((c) => c.id !== cred.id);
    filtered.push(cred);

    const { error } = await supabaseAdmin.from("settings").upsert({
      id: "admin_biometric_credentials",
      store_name: JSON.stringify(filtered),
    });

    if (error) {
      console.error("[Biometrics] Failed to save credential to Supabase:", error);
      return false;
    }

    return true;
  } catch (err) {
    console.error("[Biometrics] Error persisting biometric credential:", err);
    return false;
  }
}

/**
 * Removes a specific biometric credential or deletes all if none specified
 */
export async function deleteBiometricCredential(credId?: string): Promise<boolean> {
  if (!isSupabaseConfigured || !supabaseAdmin) {
    return false;
  }

  try {
    if (!credId) {
      await supabaseAdmin.from("settings").delete().eq("id", "admin_biometric_credentials");
      return true;
    }

    const existing = await getEnrolledBiometricCredentials();
    const updated = existing.filter((c) => c.id !== credId);

    const { error } = await supabaseAdmin.from("settings").upsert({
      id: "admin_biometric_credentials",
      store_name: JSON.stringify(updated),
    });

    return !error;
  } catch (err) {
    console.error("[Biometrics] Error deleting credential:", err);
    return false;
  }
}

/**
 * Updates lastUsedAt on successful biometric authentication
 */
export async function recordBiometricUsage(credId: string): Promise<void> {
  try {
    const existing = await getEnrolledBiometricCredentials();
    const matched = existing.find((c) => c.id === credId);
    if (matched) {
      matched.lastUsedAt = new Date().toISOString();
      await supabaseAdmin?.from("settings").upsert({
        id: "admin_biometric_credentials",
        store_name: JSON.stringify(existing),
      });
    }
  } catch (_) {}
}
