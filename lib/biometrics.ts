import crypto from "crypto";
import { supabaseAdmin, isSupabaseConfigured } from "./supabase";

export interface BiometricCredential {
  id: string; // Base64URL credential ID
  email: string;
  deviceName: string;
  publicKey?: string;
  counter?: number;
  createdAt: string;
  lastUsedAt?: string;
}

// Stateless HMAC-signed challenge generator for WebAuthn
const CHALLENGE_TTL_MS = 5 * 60 * 1000;
const BIOMETRIC_SECRET =
  process.env.ADMIN_SECRET_KEY ||
  process.env.ADMIN_PASSWORD ||
  "bmgh-biometric-secure-key-2026";

/**
 * Creates a cryptographically random, stateless HMAC-signed challenge for WebAuthn ceremonies.
 * Guaranteed to verify across all Vercel serverless lambda instances.
 */
export function createBiometricChallenge(type: "register" | "auth" = "auth"): string {
  const timestamp36 = Date.now().toString(36);
  const nonce = crypto.randomBytes(16).toString("base64url");
  const payload = `${type}.${timestamp36}.${nonce}`;
  const sig = crypto.createHmac("sha256", BIOMETRIC_SECRET).update(payload).digest("base64url");
  return `${payload}.${sig}`;
}

/**
 * Verifies that a challenge was legitimately generated by the server and has not expired (5 min TTL)
 */
export function consumeBiometricChallenge(challenge: string): boolean {
  if (!challenge || typeof challenge !== "string") return false;
  const parts = challenge.split(".");
  if (parts.length !== 4) return false;
  const [type, timestamp36, nonce, sig] = parts;
  const payload = `${type}.${timestamp36}.${nonce}`;
  const expectedSig = crypto.createHmac("sha256", BIOMETRIC_SECRET).update(payload).digest("base64url");
  if (sig !== expectedSig) return false;
  const timestamp = parseInt(timestamp36, 36);
  if (isNaN(timestamp) || Date.now() - timestamp > CHALLENGE_TTL_MS) {
    return false; // Expired
  }
  return true;
}

// In-memory credential fallback
const globalBiometrics = globalThis as unknown as {
  __bmgh_biometrics?: BiometricCredential[];
};
if (!globalBiometrics.__bmgh_biometrics) {
  globalBiometrics.__bmgh_biometrics = [];
}

/**
 * Retrieves all registered biometric credentials from Supabase settings
 */
export async function getEnrolledBiometricCredentials(): Promise<BiometricCredential[]> {
  if (isSupabaseConfigured && supabaseAdmin) {
    try {
      const { data, error } = await supabaseAdmin
        .from("settings")
        .select("store_name")
        .eq("id", "admin_biometric_credentials")
        .maybeSingle();

      if (!error && data?.store_name) {
        const parsed = JSON.parse(data.store_name);
        if (Array.isArray(parsed)) {
          globalBiometrics.__bmgh_biometrics = parsed;
          return parsed;
        }
      }
    } catch (err) {
      console.warn("[Biometrics] Error fetching biometric credentials:", err);
    }
  }

  return globalBiometrics.__bmgh_biometrics || [];
}

/**
 * Enrolls a new biometric credential into Supabase settings
 */
export async function saveBiometricCredential(cred: BiometricCredential): Promise<boolean> {
  const existing = await getEnrolledBiometricCredentials();
  const filtered = existing.filter((c) => c.id !== cred.id);
  filtered.push(cred);
  globalBiometrics.__bmgh_biometrics = filtered;

  if (isSupabaseConfigured && supabaseAdmin) {
    try {
      const { error } = await supabaseAdmin.from("settings").upsert({
        id: "admin_biometric_credentials",
        store_name: JSON.stringify(filtered),
        email: "admin@bundlemartgh.com",
        support_phone: "+233 55 123 4567",
        whatsapp_number: "233551234567",
      });

      if (error) {
        console.error("[Biometrics] Failed to save credential to Supabase:", error);
      }
    } catch (err) {
      console.error("[Biometrics] Error persisting biometric credential:", err);
    }
  }

  return true;
}

/**
 * Removes a specific biometric credential or deletes all if none specified
 */
export async function deleteBiometricCredential(credId?: string): Promise<boolean> {
  if (!credId) {
    globalBiometrics.__bmgh_biometrics = [];
    if (isSupabaseConfigured && supabaseAdmin) {
      try {
        await supabaseAdmin.from("settings").delete().eq("id", "admin_biometric_credentials");
      } catch (_) {}
    }
    return true;
  }

  const existing = await getEnrolledBiometricCredentials();
  const updated = existing.filter((c) => c.id !== credId);
  globalBiometrics.__bmgh_biometrics = updated;

  if (isSupabaseConfigured && supabaseAdmin) {
    try {
      await supabaseAdmin.from("settings").upsert({
        id: "admin_biometric_credentials",
        store_name: JSON.stringify(updated),
      });
    } catch (_) {}
  }

  return true;
}

/**
 * Updates lastUsedAt on successful biometric authentication
 */
export async function recordBiometricUsage(credId: string): Promise<void> {
  try {
    const existing = await getEnrolledBiometricCredentials();
    const matched = existing.find((c) => c.id === credId);
    if (matched) {
      matched.lastUsedAt = new Date().toISOString();
      await supabaseAdmin?.from("settings").upsert({
        id: "admin_biometric_credentials",
        store_name: JSON.stringify(existing),
      });
    }
  } catch (_) {}
}

